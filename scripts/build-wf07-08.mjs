      '**Alpaca Paper** (prices + clock) and **Frankfurter** (FX) are optional: on any error the Code falls back to last fill prices, `market_open: null` and config `fx_fallback_usdcad`. Positions are always derived from the user\'s own `orders` rows, because every user shares one paper account.',
