#!/usr/bin/env node
// Generates Lane E's workflows so their Code nodes always carry lib/week.mjs + lib/projection.mjs
// verbatim (spec §19.6), the same way scripts/build-wf00.mjs builds LO-00:
//
//   node scripts/build-wf07-08.mjs          writes n8n/workflows/07-weekly-digest.json + 08-dashboard-api.json
//   node scripts/build-wf07-08.mjs --dev    also adds the dev-only POST /lo/dev-e/seed-test-e route to LO-08
//                                           (rewrites test-e's rows; push, call once, then rebuild without --dev and push)
//
// Then: node scripts/n8n.mjs push n8n/workflows/08-dashboard-api.json (and 07-…).
//
// LO-08 Dashboard API (spec §10 WF08, contracts/api.md): five webhook rows, each
//   Webhook -> Data Table reads (filtered by user_id) -> [Alpaca + FX lookups] -> Code (lib) -> Respond
// LO-07 Weekly Digest (spec §10 WF07, §19.5): webhook + Execute Workflow Trigger -> reads -> facts ->
//   LLM summary (template fallback) -> Gmail (skipped on dry_run) -> envelope for the webhook / data for LO-04.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const DEV = process.argv.includes('--dev');
const versions = JSON.parse(readFileSync(join(root, 'n8n/templates/node-versions.json'), 'utf8')).nodes;
const ids = JSON.parse(readFileSync(join(root, 'n8n/ids.json'), 'utf8'));
const stripExport = (src) => src.replace(/^export\s*\{[\s\S]*?\};?\s*$/m, '').trim();
const LIB = [
  '// ---- lib/week.mjs (verbatim) ----',
  stripExport(readFileSync(join(root, 'lib/week.mjs'), 'utf8')),
  '// ---- lib/projection.mjs (verbatim) ----',
  stripExport(readFileSync(join(root, 'lib/projection.mjs'), 'utf8')),
].join('\n\n');
const GENERATED = '// GENERATED by scripts/build-wf07-08.mjs from lib/week.mjs + lib/projection.mjs.\n// Don\'t edit in n8n: change the lib or the builder, rebuild, push.';

const T = (k) => versions[k].type;
const V = (k) => versions[k].latest;
const HOOK_CRED = { httpHeaderAuth: { id: ids.credentials.lo_webhook_key, name: 'LO Webhook Key' } };
// Third-party credentials (spec §0.3): `n8n publish:workflow` rejects a credential that doesn't exist
// ("uses invalid credential"), so a node gets its credential only once its id is in n8n/ids.json
// (credentials.alpaca_paper / llm / gmail). Until then the node keeps its auth type with nothing
// attached, fails fast at run time, and the flow falls back (spec §19.5).
const cred = (idKey, type, name) => (ids.credentials[idKey] ? { [type]: { id: ids.credentials[idKey], name } } : null);
const ALPACA_CRED = cred('alpaca_paper', 'httpCustomAuth', 'Alpaca Paper');
const LLM_CRED = cred('llm', 'anthropicApi', 'LLM');
const GMAIL_CRED = cred('gmail', 'gmailOAuth2', 'Gmail');
const PAPER = 'https://paper-api.alpaca.markets';

let uuidSeq = 0;
// Stable, valid UUIDs so rebuilding never changes webhook URLs or If-condition ids.
const uuid = (tag) => {
  uuidSeq += 1;
  const hex = Buffer.from(`${tag}:${uuidSeq}`).toString('hex').padEnd(32, '0').slice(0, 32);
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-8${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
};

// ---------- node factories (shapes from n8n/templates/node-snippets.json + node-types.json) ----------
function webhook(name, method, path, webhookId, position, responseMode = 'responseNode') {
  const parameters = { httpMethod: method, path, authentication: 'headerAuth', responseMode, options: {} };
  if (responseMode === 'lastNode') parameters.responseData = 'firstEntryJson';
  return { parameters, name, type: T('webhook'), typeVersion: V('webhook'), position, webhookId, credentials: HOOK_CRED };
}
function code(name, jsCode, position) {
  return { parameters: { jsCode }, name, type: T('code'), typeVersion: V('code'), position };
}
function dtGet(name, table, userIdExpr, position) {
  const parameters = { resource: 'row', operation: 'get', dataTableId: { __rl: true, mode: 'name', value: table } };
  if (userIdExpr) parameters.matchType = 'allConditions', parameters.filters = { conditions: [{ keyName: 'user_id', condition: 'eq', keyValue: userIdExpr }] };
  parameters.returnAll = true;
  return { parameters, name, type: T('dataTable'), typeVersion: V('dataTable'), position, executeOnce: true, alwaysOutputData: true };
}
function dtUpdate(name, table, conditions, position, executeOnce = false) {
  return {
    parameters: {
      resource: 'row', operation: 'update', dataTableId: { __rl: true, mode: 'name', value: table }, matchType: 'allConditions',
      filters: { conditions: conditions.map(([keyName, keyValue]) => ({ keyName, condition: 'eq', keyValue })) },
      columns: { mappingMode: 'autoMapInputData', value: {}, matchingColumns: [], schema: [] }, options: {},
    },
    name, type: T('dataTable'), typeVersion: V('dataTable'), position, alwaysOutputData: true, ...(executeOnce ? { executeOnce: true } : {}),
  };
}
function dtDelete(name, table, userId, position) {
  return {
    parameters: {
      resource: 'row', operation: 'deleteRows', dataTableId: { __rl: true, mode: 'name', value: table }, matchType: 'allConditions',
      filters: { conditions: [{ keyName: 'user_id', condition: 'eq', keyValue: userId }] }, options: {},
    },
    name, type: T('dataTable'), typeVersion: V('dataTable'), position, executeOnce: true, alwaysOutputData: true,
  };
}
function dtInsert(name, table, position) {
  return {
    parameters: {
      resource: 'row', operation: 'insert', dataTableId: { __rl: true, mode: 'name', value: table },
      columns: { mappingMode: 'autoMapInputData', value: {}, matchingColumns: [], schema: [] }, options: {},
    },
    name, type: T('dataTable'), typeVersion: V('dataTable'), position,
  };
}
function http(name, url, query, position, credentials) {
  const parameters = { url };
  if (credentials !== undefined) parameters.authentication = 'genericCredentialType', parameters.genericAuthType = 'httpCustomAuth';
  if (query) parameters.sendQuery = true, parameters.queryParameters = { parameters: query.map(([n, v]) => ({ name: n, value: v })) };
  parameters.options = { timeout: 4000 };
  return {
    parameters, name, type: T('httpRequest'), typeVersion: V('httpRequest'), position,
    executeOnce: true, onError: 'continueRegularOutput', ...(credentials ? { credentials } : {}),
  };
}
function ifTrue(name, leftValue, position) {
  return {
    parameters: {
      conditions: {
        options: { caseSensitive: true, leftValue: '', typeValidation: 'loose', version: 4 },
        conditions: [{ id: uuid(name), leftValue, rightValue: '', operator: { type: 'boolean', operation: 'true', singleValue: true } }],
        combinator: 'and',
      },
      looseTypeValidation: true,
      options: {},
    },
    name, type: T('if'), typeVersion: V('if'), position,
  };
}
function respond(name, position) {
  return {
    parameters: { respondWith: 'json', responseBody: '={{ $json.body }}', options: { responseCode: '={{ $json.status }}' } },
    name, type: T('respondToWebhook'), typeVersion: V('respondToWebhook'), position,
  };
}
function sticky(name, content, position, width, height, color) {
  return { parameters: { content, width, height, ...(color ? { color } : {}) }, name, type: T('stickyNote'), typeVersion: V('stickyNote'), position };
}

// connections helper: link(a, b) or link(a, b, outputIndex)
function graph() {
  const connections = {};
  const link = (from, to, out = 0, type = 'main') => {
    connections[from] ??= {};
    connections[from][type] ??= [];
    while (connections[from][type].length <= out) connections[from][type].push([]);
    connections[from][type][out].push({ node: to, type, index: 0 });
  };
  const chain = (...names) => names.slice(1).forEach((n, i) => link(names[i], n));
  return { connections, link, chain };
}

const userIdFromQuery = (hook) => `={{ String($('${hook}').first().json.query.user_id || '').trim().toLowerCase() || '-' }}`;
const userIdFromBody = (hook) => `={{ String(($('${hook}').first().json.body || {}).user_id || '').trim().toLowerCase() || '-' }}`;

// Small Code node: symbols to price + paper base URL (never a live URL).
const prepareCode = (ordersNode, configNode) => `// Symbols to price and the Alpaca paper base URL for the next HTTP nodes.
const orders = $('${ordersNode}').all().map((i) => i.json).filter((o) => o && o.symbol);
const cfg = {};
for (const i of $('${configNode}').all()) if (i.json && i.json.key) cfg[i.json.key] = i.json.value;
const base = String(cfg.alpaca_base_url || '').replace(/\\/$/, '');
return [{ json: {
  symbols: [...new Set(orders.map((o) => o.symbol))].join(','),
  alpaca_base_url: base.startsWith('${PAPER}') ? base : '${PAPER}',
} }];`;

const glue = (body) => `${GENERATED}

${LIB}

// ---- workflow glue ----
const all = (n) => $(n).all().map((i) => i.json);
const one = (n) => { try { return $(n).first().json; } catch (e) { return null; } };
try {
${body.trim().split('\n').map((l) => `  ${l}`).join('\n')}
} catch (e) {
  return [{ json: fail(500, 'INTERNAL', String((e && e.message) || e)) }];
}`;

