#!/usr/bin/env node
// Generates n8n/workflows/00-setup-and-seed.json from demo/seed-data.json and
// lib/week.mjs, so the workflow can never drift from the seed or the week math.
// Run after changing either file:  node scripts/build-wf00.mjs  then  node scripts/n8n.mjs push <file>
//
// LO-00 (spec §10 WF00, §19.4):
//   triggers: manual run + POST /lo/demo/reset (x-lo-key)
//   1. create every Data Table if missing (columns from contracts/data-tables.md)
//   2. config + category_map: rewrite from the seed, keeping demo_email_to / dashboard_url if already set
//   3. maya: delete her rows in every user table, reseed users, profiles, budgets, transactions
//   4. summary
//   5. backfill maya's past weeks through LO-04 (invest: false), then respond

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'n8n/workflows/00-setup-and-seed.json');
const conventions = JSON.parse(readFileSync(join(root, 'n8n/templates/node-versions.json'), 'utf8')).nodes;
const v = (k) => conventions[k].latest;
const T = (k) => conventions[k].type;
const ids = JSON.parse(readFileSync(join(root, 'n8n/ids.json'), 'utf8'));

// contracts/data-tables.md. Order matters only for readability.
const TABLES = {
  users: 'user_id:s email:s name:s created_at:d timezone:s status:s consent_at:d buffer_balance:n buffer_target:n cushion_rate:n absorb_overspend:b min_invest:n max_weekly_invest:n pending_carry:n deficit_carry:n',
  profiles: 'user_id:s answers_json:s capacity_score:n willingness_score:n tier:s home_bias:s allocation_json:s explanation:s updated_at:d warnings_json:s',
  budgets: 'user_id:s category_key:s label:s weekly_amount:n active:b',
  category_map: 'plaid_pfc_primary:s plaid_pfc_detailed:s category_key:s excluded:b',
  bank_links: 'user_id:s item_id:s access_token:s cursor:s institution_name:s linked_at:d',
  transactions: 'txn_id:s user_id:s date:s amount:n merchant:s pfc_primary:s pfc_detailed:s category_key:s pending:b pending_txn_id:s source:s removed:b synced_at:d',
  audits: 'audit_id:s user_id:s week_start:s week_end:s lines_json:s gross_surplus:n total_over:n late_adj:n to_buffer:n buffer_after:n investable_cad:n pending_carry_after:n status:s created_at:d',
  orders: 'client_order_id:s audit_id:s user_id:s symbol:s sleeve:s notional_usd:n notional_cad:n fx_rate:n alpaca_order_id:s status:s filled_qty:n filled_avg_price:n submitted_at:d filled_at:d',
  config: 'key:s value:s',
};
const TYPE = { s: 'string', n: 'number', b: 'boolean', d: 'date' };
const USER_TABLES = ['orders', 'audits', 'transactions', 'bank_links', 'budgets', 'profiles', 'users'];
const SEEDED = ['users', 'profiles', 'budgets', 'transactions'];
const DEMO_USER = 'maya';

const seed = JSON.parse(readFileSync(join(root, 'demo/seed-data.json'), 'utf8'));
const weekLib = readFileSync(join(root, 'lib/week.mjs'), 'utf8').replace(/^export\s*\{[\s\S]*?\};?\s*$/m, '').trim();

// Strip notes and _expected: the workflow only needs the data.
const clean = (x) => (Array.isArray(x) ? x.map(clean)
  : x && typeof x === 'object' ? Object.fromEntries(Object.entries(x).filter(([k]) => !k.startsWith('_')).map(([k, val]) => [k, clean(val)]))
    : x);
const SEED = clean(seed);

const buildSeedCode = `// GENERATED by scripts/build-wf00.mjs from demo/seed-data.json + lib/week.mjs.
// Don't edit in n8n: change those files, rebuild, push.
const SEED = ${JSON.stringify(SEED)};

${weekLib}

const now = new Date();
const nowIso = now.toISOString();
const atOffset = (days) => new Date(\`\${seedDate(days, now)}T12:00:00-07:00\`).toISOString();
const u = SEED.user;

const users = [{
  user_id: u.user_id, email: u.email, name: u.name, created_at: atOffset(u.created_day_offset),
  timezone: u.timezone, status: u.status, consent_at: atOffset(u.consent_day_offset),
  buffer_balance: u.buffer_balance, buffer_target: u.buffer_target, cushion_rate: u.cushion_rate,
  absorb_overspend: u.absorb_overspend, min_invest: u.min_invest, max_weekly_invest: u.max_weekly_invest,
  pending_carry: u.pending_carry, deficit_carry: u.deficit_carry,
}];
const p = SEED.profile;
const profiles = [{
  user_id: p.user_id, answers_json: JSON.stringify(p.answers), capacity_score: p.capacity_score,
  willingness_score: p.willingness_score, tier: p.tier, home_bias: p.home_bias,
  allocation_json: JSON.stringify(p.allocation), explanation: p.explanation, updated_at: nowIso,
  warnings_json: JSON.stringify(p.warnings),
}];
const budgets = SEED.budgets.map((b) => ({ ...b }));
const transactions = SEED.transactions.map(({ day_offset, ...t }) => ({
  ...t, date: seedDate(day_offset, now), source: 'seed', synced_at: nowIso,
}));

return [{ json: {
  week_start: weekStart(now), users, profiles, budgets, transactions,
  category_map: SEED.category_map, config: SEED.config,
} }];`;

const mergeConfigCode = `// Seed config, but keep values Wave 3 set by hand (demo_email_to, dashboard_url).
const KEEP = ['demo_email_to', 'dashboard_url'];
const existing = Object.fromEntries($input.all().filter((i) => i.json.key).map((i) => [i.json.key, i.json.value]));
return $('Build seed rows').first().json.config.map(({ key, value }) => ({
  json: { key, value: KEEP.includes(key) && existing[key] ? existing[key] : value },
}));`;

const rowsCode = (field) => `return $('Build seed rows').first().json.${field}.map((row) => ({ json: row }));`;
const configRowsCode = `return $('Merge config').all().map((i) => ({ json: i.json }));`;
const summaryCode = `const s = $('Build seed rows').first().json;
return [{ json: { ok: true, data: {
  user_id: '${DEMO_USER}', week_start: s.week_start,
  transactions_seeded: s.transactions.length, budgets_seeded: s.budgets.length,
} } }];`;

// ---------- assemble ----------
const nodes = [];
const chain = []; // linear main path after the triggers
let x = 460;
const add = (node) => { nodes.push(node); return node; };
const step = (node) => { node.position = [x, 300]; x += 220; chain.push(add(node)); return node; };
const locator = (table) => ({ __rl: true, mode: 'name', value: table });
const dataTable = (name, parameters, extra = {}) => ({ parameters, name, type: T('dataTable'), typeVersion: v('dataTable'), ...extra });
const code = (name, jsCode) => ({ parameters: { jsCode }, name, type: T('code'), typeVersion: v('code') });
const once = { executeOnce: true, alwaysOutputData: true };

add({ parameters: {}, name: 'Run manually', type: T('manualTrigger'), typeVersion: v('manualTrigger'), position: [0, 200] });
add({
  parameters: {
    httpMethod: 'POST', path: 'lo/demo/reset', authentication: 'headerAuth',
    responseMode: 'lastNode', responseData: 'firstEntryJson', options: {},
  },
  name: 'POST /lo/demo/reset', type: T('webhook'), typeVersion: v('webhook'), position: [0, 400],
  webhookId: 'a1f7c0de-1000-4000-8000-000000000000',
  credentials: { httpHeaderAuth: { id: ids.credentials.lo_webhook_key, name: 'LO Webhook Key' } },
});

for (const [table, spec] of Object.entries(TABLES)) {
  step(dataTable(`Create table ${table}`, {
    resource: 'table', operation: 'create', tableName: table,
    columns: { column: spec.split(' ').map((c) => { const [name, t] = c.split(':'); return { name, type: TYPE[t] }; }) },
    options: { createIfNotExists: true },
  }, { executeOnce: true }));
}

step(code('Build seed rows', buildSeedCode));

step(dataTable('Read config', { resource: 'row', operation: 'get', dataTableId: locator('config'), returnAll: true }, once));
step(code('Merge config', mergeConfigCode));
step(dataTable('Clear config', { resource: 'table', operation: 'clear', dataTableId: locator('config') }, once));
step(code('Config rows', configRowsCode));
step(dataTable('Insert config', { resource: 'row', operation: 'insert', dataTableId: locator('config'), columns: { mappingMode: 'autoMapInputData', value: {}, matchingColumns: [], schema: [] }, options: {} }));

step(dataTable('Clear category_map', { resource: 'table', operation: 'clear', dataTableId: locator('category_map') }, once));
step(code('Category rows', rowsCode('category_map')));
step(dataTable('Insert category_map', { resource: 'row', operation: 'insert', dataTableId: locator('category_map'), columns: { mappingMode: 'autoMapInputData', value: {}, matchingColumns: [], schema: [] }, options: {} }));

for (const table of USER_TABLES) {
  step(dataTable(`Delete ${DEMO_USER} from ${table}`, {
    resource: 'row', operation: 'deleteRows', dataTableId: locator(table), matchType: 'allConditions',
    filters: { conditions: [{ keyName: 'user_id', condition: 'eq', keyValue: DEMO_USER }] }, options: {},
  }, once));
}
for (const table of SEEDED) {
  step(code(`${table[0].toUpperCase()}${table.slice(1)} rows`, rowsCode(table)));
  step(dataTable(`Insert ${table}`, { resource: 'row', operation: 'insert', dataTableId: locator(table), columns: { mappingMode: 'autoMapInputData', value: {}, matchingColumns: [], schema: [] }, options: {} }));
}
step(code('Summary', summaryCode));

// 5. backfill: audit Maya's past seeded weeks through LO-04 with invest: false, oldest first,
//    so History has numbers right after a reset (BUILD-PLAN Wave 3 step 2). LO-04's order
//    guard needs oldest first; Execute Workflow "each" + wait runs them one after another.
const BACKFILL = seed._expected.weeks.map((w) => w.day_offset_start).sort((a, b) => a - b);
step(code('Backfill weeks', `// GENERATED by scripts/build-wf00.mjs: one item per past seeded week, oldest first.
const s = $('Build seed rows').first().json;
const OFFSETS = ${JSON.stringify(BACKFILL)};
const addDays = (ymd, n) => { const d = new Date(ymd + 'T00:00:00Z'); d.setUTCDate(d.getUTCDate() + n); return d.toISOString().slice(0, 10); };
return OFFSETS.map((o) => ({ json: { user_id: '${DEMO_USER}', week_start: addDays(s.week_start, o), invest: false } }));`));
step({
  parameters: {
    workflowId: { __rl: true, value: ids.workflows['LO-04'], mode: 'id', cachedResultName: 'LO-04 Weekly Audit' },
    mode: 'each', options: { waitForSubWorkflow: true },
  },
  name: 'Backfill audits (LO-04)', type: T('executeWorkflow'), typeVersion: v('executeWorkflow'), onError: 'continueRegularOutput',
});
step(code('Reply', `// LO-04 hands back its last node's item: { status, body } (body = the /lo/audit/run envelope).
const summary = $('Summary').first().json;
const backfilled = $input.all().map(({ json: j }) => {
  const a = j && j.body && j.body.data && j.body.data.audits && j.body.data.audits[0];
  if (a) return { audit_id: a.audit_id, status: a.status, investable_cad: a.investable_cad, buffer_after_cad: a.buffer_after_cad };
  return { error: (j && j.body && j.body.error) || (j && j.error) || { code: 'INTERNAL', message: 'LO-04 returned nothing' } };
});
return [{ json: { ...summary, data: { ...summary.data, backfilled } } }];`));

const connections = {};
const link = (from, to) => { connections[from] = { main: [[{ node: to, type: 'main', index: 0 }]] }; };
link('Run manually', chain[0].name);
link('POST /lo/demo/reset', chain[0].name);
for (let i = 0; i < chain.length - 1; i++) link(chain[i].name, chain[i + 1].name);

const wf = {
  id: ids.workflows['LO-00'],
  name: 'LO-00 Setup and Seed',
  active: true,
  nodes,
  connections,
  settings: { executionOrder: 'v1', timezone: 'America/Vancouver', errorWorkflow: ids.workflows['LO-09'] },
  staticData: null,
};
writeFileSync(OUT, `${JSON.stringify(wf, null, 2)}\n`);
console.log(`wrote ${OUT}: ${nodes.length} nodes`);
